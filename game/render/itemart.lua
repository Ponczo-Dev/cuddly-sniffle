local ICONS = {}

local function rgb(c) return { c[1], c[2], c[3] } end

-- Generuje ikonę przedmiotu na podstawie definicji (d.icon, d.iconMaterial, d.iconColor)
function M.generate(def, damage)
  local key = def.icon or "blob"
  local tmpl = TEMPLATES[key]
  if tmpl then
    return texturegen.art(tmpl, matPalette(def.iconMaterial or "iron"))
  end
  local simple = SIMPLE[key]
  local pal
  local function colorBlob(c)
    local s = SIMPLE.blob
    local p = {
      o = { c[1] * 0.4, c[2] * 0.4, c[3] * 0.4 }, m = rgb(c),
      M = { math.min(255, c[1] * 1.3 + 30), math.min(255, c[2] * 1.3 + 30),
        math.min(255, c[3] * 1.3 + 30) },
      d = { c[1] * 0.75, c[2] * 0.75, c[3] * 0.75 },
    }
    return texturegen.art(s.rows, p)
  end
  local function colorDust(c)
    return texturegen.art(SIMPLE.dust.rows, { m = rgb(c),
      M = { math.min(255, c[1] + 50), math.min(255, c[2] + 50), math.min(255, c[3] + 50) } })
  end

  if key == "coal" and damage == 1 then
    return texturegen.art(SIMPLE.coal.rows, { o = { 30, 20, 10 }, m = { 70, 50, 30 },
      M = { 110, 85, 55 }, d = { 50, 35, 20 } })
  end
  if key == "ingot" then
    local c = def.iconColor or { 200, 200, 200 }
    return texturegen.art(SIMPLE.ingot.rows, { o = { c[1] * 0.4, c[2] * 0.4, c[3] * 0.4 },
      m = rgb(c), M = { math.min(255, c[1] + 40), math.min(255, c[2] + 40), math.min(255, c[3] + 40) },
      d = { c[1] * 0.7, c[2] * 0.7, c[3] * 0.7 } })
  end
  local MEATS = {
    raw_porkchop = { { 120, 50, 50 }, { 240, 140, 140 }, { 255, 185, 185 } },
    cooked_porkchop = { { 80, 40, 20 }, { 170, 110, 60 }, { 210, 150, 90 } },
    raw_beef = { { 110, 20, 20 }, { 200, 50, 45 }, { 235, 100, 90 } },
    steak = { { 60, 30, 15 }, { 130, 80, 40 }, { 170, 115, 65 } },
    rotten_flesh = { { 70, 60, 25 }, { 130, 110, 50 }, { 160, 140, 70 } },
  }
  if MEATS[key] then
    local c = MEATS[key]
    local p = { o = c[1], m = c[2], M = c[3], w = { 240, 230, 220 }, W = { 255, 255, 255 } }
    return texturegen.art(SIMPLE.meat.rows, p)
  end
  if key == "raw_chicken" or key == "cooked_chicken" then
    local c = key == "raw_chicken" and { { 150, 110, 100 }, { 245, 205, 190 }, { 255, 230, 220 } }
      or { { 110, 60, 20 }, { 210, 150, 70 }, { 240, 190, 110 } }
    return texturegen.art(SIMPLE.chickenleg.rows, { o = c[1], m = c[2], M = c[3],
      w = { 240, 230, 220 }, W = { 255, 255, 255 } })
  end
  if key == "bucket" or key == "water_bucket" or key == "lava_bucket" or key == "milk_bucket" then
    local liquid = { bucket = { 70, 70, 70 }, water_bucket = { 50, 80, 230 },
      lava_bucket = { 240, 120, 20 }, milk_bucket = { 250, 250, 250 } }
    local p = {}
    for k, v in pairs(SIMPLE.bucket.pal) do p[k] = v end
    p.L = liquid[key]
    return texturegen.art(SIMPLE.bucket.rows, p)
  end
  if key == "bowl" or key == "mushroom_stew" then
    local p = {}
    for k, v in pairs(SIMPLE.bowl.pal) do p[k] = v end
    p.L = key == "mushroom_stew" and { 170, 110, 70 } or { 120, 80, 35 }
    return texturegen.art(SIMPLE.bowl.rows, p)
  end
  if key == "golden_apple" then
    local p = {}
    for k, v in pairs(SIMPLE.apple.pal) do p[k] = v end
    p.r, p.R, p.d, p.w = { 230, 200, 40 }, { 255, 240, 120 }, { 170, 130, 20 }, { 255, 255, 200 }
    return texturegen.art(SIMPLE.apple.rows, p)
  end
  if key == "dye" then
    local DYE = { [0] = { 30, 30, 30 }, [1] = { 200, 40, 40 }, [2] = { 60, 120, 40 },
      [3] = { 110, 70, 40 }, [4] = { 40, 70, 190 }, [11] = { 230, 210, 50 }, [15] = { 240, 240, 230 } }
    return colorDust(DYE[damage or 0] or { 150, 150, 150 })
  end
  local BLOBS = {
    snowball = { 240, 245, 250 }, clay_ball = { 160, 166, 179 }, slimeball = { 110, 190, 90 },
    ender_pearl = { 30, 110, 100 }, leather = { 140, 90, 45 },
  }
  if BLOBS[key] then return colorBlob(BLOBS[key]) end
  if key == "brick" then
    return texturegen.art(SIMPLE.ingot.rows, { o = { 60, 25, 15 }, m = { 160, 75, 55 },
      M = { 200, 110, 85 }, d = { 120, 55, 40 } })
  end
  if key == "redstone" then return colorDust({ 200, 15, 15 }) end
  if key == "sugar" then return colorDust({ 245, 245, 245 }) end
  if simple then
    pal = simple.pal
    return texturegen.art(simple.rows, pal)
  end
  return colorBlob({ 200, 0, 200 })
end

